pub fn is_class(name: &str) -> bool {
    CLASSES.binary_search(&name).is_ok()
}

/// The creatable classes that are a GuiObject: a layout places them, and
/// they have `LayoutOrder`. A UICorner or a UIScale is none of them.
pub fn is_gui_object(name: &str) -> bool {
    matches!(
        name,
        "CanvasGroup"
            | "Frame"
            | "ImageButton"
            | "ImageLabel"
            | "ScrollingFrame"
            | "TextBox"
            | "TextButton"
            | "TextLabel"
            | "VideoFrame"
            | "ViewportFrame"
    )
}

#[cfg(test)]
mod tests {
    #[test]
    fn the_list_is_sorted_and_holds_the_gui_classes() {
        assert!(super::CLASSES.windows(2).all(|w| w[0] < w[1]));
        assert!(super::is_class("Frame"));
        assert!(super::is_class("StyleLink"));
        assert!(!super::is_class("Card"));
    }
}
